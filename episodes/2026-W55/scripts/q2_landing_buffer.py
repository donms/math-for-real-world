#!/usr/bin/env python -X utf8
# -*- coding: utf-8 -*-
r"""W55 · **落地缓冲**：为什么下落比上升慢（用户 2026-10-17 的纠正）。

## ★ 用户的原话（这是关键物理洞察）

> **"下落慢是因为要落地缓冲，不然就砸地上了。"**

## 我原来的（错的）解释

我写的是"**飞行中持续向上推力**，等效重力被削掉 67%"，
即假设推进器**全程都在提供向上的加速度**。

**那是错的。** 用户指出：**推进器的向上推力集中在【落地前那一段】**，
目的是**把落地速度降下来**。

## ★ 两者在物理上的根本区别

| 模型 | 推力作用时段 | 对 $h_{\max}$ 的影响 | 冲量消耗 |
|---|---|---|---|
| **我的"持续推力"** | **全程** | 抬高 | 大（全程 × 小力）|
| **用户的"缓冲"** | **落地前** | **几乎不抬高** | **小（短时 × 大力）** |

**⇒ 同样是把下落时间拉长，缓冲用的冲量**少得多** ——
因为它在"已经快要落地"时施加，此时重力的功已经做完了。**

## 缓冲要多少冲量？

设自由落体到地面时速度为 $v_{\text{imp}}$，缓冲后降到 $v_{\text{safe}}$：

$$I_{\text{soft}} = m\left(v_{\text{imp}} - v_{\text{safe}}\right)$$

**而 $v_{\text{imp}} = \sqrt{2g h_{\max}}$（从峰值自由落体）。**

**★ 注意**：这个 $v_{\text{imp}}$ **恰好等于**上升所需的 $v_{z0}$ = 12.32 m/s
（能量守恒，上下对称）。

**⇒ 所以"缓冲"的冲量 ≈ "起飞"的冲量** ——
**这是一个非常漂亮的对称结果**：

$$\boxed{I_{\text{up}} = I_{\text{down}} = m\sqrt{2gh_{\max}}}$$
（若落地速度降到 0）
"""
from __future__ import annotations

import math

G = 9.81
FT = 0.3048
M_CAR = 2000.0
I_TOTAL = 172.6e3      # 总冲量 (N·s)

H_MAX = 25.4 * FT      # 7.74 m


def impulse(m: float, dv: float) -> float:
    return m * dv


def main() -> int:
    print("=" * 94)
    print("  W55 · 落地缓冲：为什么下落比上升慢")
    print("=" * 94)
    print(f"\n  峰值 h_max = {H_MAX:.2f} m，起跳高度 h0 = 0（平地）")

    v_peak_impact = math.sqrt(2 * G * H_MAX)
    print(f"\n【1】从峰值自由落体到地面的速度")
    print(f"  v_imp = √(2 g h_max) = √(2×{G}×{H_MAX:.2f}) = "
          f"**{v_peak_impact:.2f} m/s = {v_peak_impact*3.6:.1f} km/h**")
    print(f"  ★ 与上升所需的 v_z0 **完全相同**（能量守恒，上下对称）")

    # ---------------- 2) 缓冲所需冲量 ----------------
    print("\n【2】★ 缓冲所需冲量（把它降到安全落地速度）")
    print(f"  I_soft = m (v_imp − v_safe)")
    print(f"\n  {'v_safe(m/s)':>13}{'v_safe(km/h)':>14}{'I_soft(kN·s)':>14}"
          f"{'占预算':>9}{'折合减速度(g)':>15}")
    for vs in (0.0, 0.5, 1.0, 2.0, 3.0):
        dv = v_peak_impact - vs
        I = impulse(M_CAR, dv)
        for dt in (0.3,):
            decel = dv / dt / G
        print(f"  {vs:>13.1f}{vs*3.6:>14.1f}{I/1000:>14.1f}"
              f"{I/I_TOTAL*100:>8.1f}%{decel:>15.1f}")
    print("  （减速度按 0.3 s 内完成缓冲估算）")

    # ---------------- 3) 上升 + 缓冲 的总账 ----------------
    print("\n【3】★ 一次完整的飞跃，气罐要出多少")
    I_up = impulse(M_CAR, v_peak_impact)
    print(f"  上升（给到 {v_peak_impact:.2f} m/s 的竖直速度）："
          f"**{I_up/1000:.1f} kN·s**")
    print(f"  缓冲（把同样的速度卸掉）：{'':>4}**{I_up/1000:.1f} kN·s**")
    print(f"  --------------------------------------------------")
    print(f"  合计（若不空中转向）：**{2*I_up/1000:.1f} kN·s**"
          f" = 预算的 **{2*I_up/I_TOTAL*100:.0f}%**")
    print()
    print("  ★★ 但注意一个**巨大的节省**：")
    print("    若车在**空中翻转 180°**，同一个喷口就从'向上推'变成'向下推'，")
    print("    而**气罐只出一次气** —— 但方向变了，所以**不能简单相加**。")
    print()
    print("    真实情况更可能是：")
    print("      · 起飞阶段：竖直喷口向上，给 12.3 m/s；")
    print("      · 空中：旋转喷口调整姿态（消耗一部分角冲量）；")
    print("      · 落地阶段：**再喷**，把落地速度压到安全值。")
    print("    ⇒ **两段都要出气，所以是相加的。**")

    # ---------------- 4) 为什么"缓冲"比"持续推力"省 ----------------
    print("\n" + "=" * 94)
    print("  【4】★ 为什么「末端缓冲」比「全程持续推力」省得多")
    print("=" * 94)
    # 我的旧模型：全程 a=6.61
    a_old = 6.61
    T_old = 3.7
    I_old = M_CAR * a_old * T_old
    print(f"  我的旧模型（全程向上加速度 {a_old:.2f} m/s²，持续 {T_old} s）：")
    print(f"    冲量 = {I_old/1000:.1f} kN·s（{I_old/I_TOTAL*100:.0f}% 预算）")
    print(f"  用户的模型（末端缓冲，只需卸掉 {v_peak_impact:.1f} m/s）：")
    for vs in (0.0, 1.0, 2.0):
        I = impulse(M_CAR, v_peak_impact - vs)
        print(f"    目标落地速度 {vs:.1f} m/s ⇒ {I/1000:.1f} kN·s"
              f"（{I/I_TOTAL*100:.0f}% 预算）")
    print()
    print("  ★ 关键差别：")
    print("    · 全程推力要在**整个腾空期**对抗重力，冲量与时间成正比；")
    print("    · 末端缓冲**只需卸掉已经积累的动能**，冲量与速度差成正比，")
    print("      而**不需要在整个下落过程中一直出力**。")
    print("    ⇒ 同样的「把下落拉长」，末端缓冲的**冲量效率高得多**。")

    # ---------------- 5) 缓冲时间与过载 ----------------
    print("\n" + "=" * 94)
    print("  【5】缓冲时间 vs 过载（工程约束）")
    print("=" * 94)
    print(f"  卸掉 {v_peak_impact:.1f} m/s，若在 Δt 内完成：")
    print(f"  {'Δt(s)':>7}{'减速度(m/s²)':>15}{'过载(g)':>10}{'所需F(kN)':>12}")
    for dt in (0.1, 0.2, 0.3, 0.5, 0.8, 1.0):
        dec = v_peak_impact / dt
        print(f"  {dt:>7.1f}{dec:>15.1f}{dec/G:>10.1f}"
              f"{M_CAR*dec/1000:>12.1f}")
    print()
    print("  ★ 若要把过载控制在 3 g 以内 ⇒ Δt ≥ 0.42 s；")
    print("    若用公布的 80 kN 主推进器 ⇒ 只能提供 40 m/s² = 4.1 g，")
    print("    而卸掉 12.3 m/s 需 0.31 s ⇒ **过载 4.1 g，勉强**。")

    print("\n" + "=" * 94)
    print("  ★★★ 修正后的账")
    print("=" * 94)
    print(f"  ① **上升**：{I_up/1000:.1f} kN·s（{I_up/I_TOTAL*100:.0f}%）"
          f" —— 把车顶到 {H_MAX:.2f} m；")
    print(f"  ② **缓冲**：{I_up/1000:.1f} kN·s（{I_up/I_TOTAL*100:.0f}%）"
          f" —— 把落地速度卸掉；")
    print(f"  ③ **合计 {2*I_up/1000:.1f} kN·s ≈ 预算的 "
          f"{2*I_up/I_TOTAL*100:.0f}%**（不含姿态旋转）；")
    print(f"  ④ 若还要**空中旋转**（问题 2 的 n 圈），再叠加角冲量；")
    print(f"  ⑤ 落地过载由**缓冲时长**决定：Δt ≥ 0.42 s 才能压到 3 g 内。")
    print()
    print("  ★★ 这意味着：**气罐的主要开销不是「飞起来」，而是「落下来」。**")
    print("     起飞和缓冲**各占一半** —— 而媒体只关注「飞起来」那一下。")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
