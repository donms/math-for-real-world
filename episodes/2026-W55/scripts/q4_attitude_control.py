#!/usr/bin/env python -X utf8
# -*- coding: utf-8 -*-
r"""W55 · **空中调姿**：10 个喷口怎么配合把车转过来（这才是真问题）。

## 用户提出的两个姿态要求（关键约束）

| 场景 | 需要的旋转 | 起始姿态 | 终止姿态 |
|---|---|---|---|
| **倒挂段**（问题 1）| **半圈（180°）** | 完全倒置（车顶朝地）| 正立（车顶朝天）|
| **飞跃**（问题 2）| **一整圈（360°）** | 正立 | 正立 |

**★ 这两个"角度要求"完全改变了问题**：
不是"转得好看"，而是 **"必须精确停在某个角度上，否则落地就翻车"**。

## 为什么"半圈"比"整圈"难

| | 半圈（180°）| 整圈（360°）|
|---|---|---|
| 目标姿态 | **倒→正**（唯一解）| **正→正**（可整圈回原位）|
| 误差后果 | **落地时车顶朝地 ⇒ 直接翻车** | 转不足/转过都能靠**视觉修正**（对称性好）|
| 对控制的敏感度 | ★ **高**（±15° 就可能撞顶）| 中 |

**⇒ 半圈是"定位问题"，整圈是"回转问题"。**

## ★ 10 个喷口怎么分工（本脚本的核心）

已知布局（媒体描述 + 物理必需）：

| 位置 | 数量 | 作用 |
|---|---|---|
| **车尾主推进器** | 1（大）| 沿车身纵轴**向前**推（加速/抬升）|
| **车头/车前** | 2 | 反推（减速/俯仰配平）|
| **车侧（左右）** | 4 | **偏航/滚转**的力偶 |
| **车底（朝下）** | 2 | **竖直抬升**（问题 2 的起飞）|
| **车顶（朝上）** | 1 | **倒挂时**朝地面推（问题 1 的脱离）|

**⇒ 关键洞察**：
**要产生"纯力偶"（转动而不平动），必须成对、反向、等量地点火。**
单个喷口点火会同时产生**平动**，必须用**配对喷口**抵消。

**这就是"10 个喷口"的物理必要性**：
单喷口只能给 1 个推力矢量；**要 3 轴姿态 + 3 轴平动 = 6 个自由度**，
而每对反作用需要 2 个喷口 ⇒ **至少 6–12 个**才够用。
"""
from __future__ import annotations

import math

G = 9.81
M_CAR = 2000.0
L_CAR = 4.5          # m 车长
W_CAR = 2.0          # m 车宽
H_CAR = 1.2          # m 车高

# 转动惯量（长方体近似）
J_PITCH = M_CAR * (L_CAR ** 2 + H_CAR ** 2) / 12.0   # 绕横轴（y）
J_ROLL = M_CAR * (W_CAR ** 2 + H_CAR ** 2) / 12.0    # 绕纵轴（x）
J_YAW = M_CAR * (L_CAR ** 2 + W_CAR ** 2) / 12.0     # 绕竖轴（z）


def main() -> int:
    print("=" * 94)
    print("  W55 · 空中调姿：10 个喷口怎么配合")
    print("=" * 94)

    print(f"\n  车体 {L_CAR}×{W_CAR}×{H_CAR} m，{M_CAR:.0f} kg")
    print(f"  转动惯量：")
    print(f"    J_pitch（绕横轴）= mL²+H²/12 = **{J_PITCH:.0f} kg·m²**")
    print(f"    J_roll （绕纵轴）= mW²+H²/12 = **{J_ROLL:.0f} kg·m²**")
    print(f"    J_yaw  （绕竖轴）= mL²+W²/12 = **{J_YAW:.0f} kg·m²**")
    print(f"  ★ 三者比例 {J_PITCH:.0f} : {J_ROLL:.0f} : {J_YAW:.0f}"
          f" = {J_PITCH/J_ROLL:.1f} : 1 : {J_YAW/J_ROLL:.1f}")
    print(f"  ⇒ **绕纵轴（滚转/桶滚）最省力** —— 因为车「又长又窄」，"
          f"绕它自己的长轴转惯性最小。")

    # ---------------- 1) 两种场景的角冲量 ----------------
    print("\n" + "=" * 94)
    print("【1】两种场景的角冲量需求")
    print("=" * 94)
    # 腾空时间
    hmax = 7.74
    T_fly_flat = 2 * math.sqrt(2 * G * hmax) / G      # 平地 2.51 s
    print(f"  腾空时间（平地 7.74 m）：T = 2√(2h/g) = {T_fly_flat:.2f} s")
    print()
    print(f"  {'场景':<28}{'角度':>8}{'所需 ω(rad/s)':>15}"
          f"{'角冲量(kg·m²/s)':>18}")
    for name, ang, axis_J in (
        ("倒挂：半圈（俯仰）", math.pi, J_PITCH),
        ("飞跃：整圈（俯仰）", 2 * math.pi, J_PITCH),
        ("飞跃：整圈（滚转）★", 2 * math.pi, J_ROLL),
    ):
        omega = ang / T_fly_flat
        L_ang = axis_J * omega
        print(f"  {name:<28}{math.degrees(ang):>7.0f}°{omega:>15.3f}"
              f"{L_ang:>18.0f}")

    print(f"\n  ★ 滚转（桶滚）比俯仰省 **{J_PITCH/J_ROLL:.1f} 倍** 角动量")

    # ---------------- 2) 力偶需要多大的力 ----------------
    print("\n" + "=" * 94)
    print("【2】★ 力偶需要多大的推力（这是「10 个喷口」的由来）")
    print("=" * 94)
    print("  要产生**纯力偶**（转动不平动），必须**成对、反向、等量**点火。")
    print("  力臂 r 处一对喷口各出 F ⇒ 力矩 M = 2 F r")
    print()
    # 典型力臂
    print(f"  {'力臂 r(m)':>10}{'要 M=1000 N·m 时 F(N)':>22}")
    for r in (0.3, 0.5, 1.0, 1.5, 2.25):
        print(f"  {r:>10.2f}{1000/(2*r):>22.1f}")
    print()
    print(f"  以「半圈 + 0.5 s 内完成」为例，需要 M = J·ω/t")
    for t in (0.3, 0.5, 0.8, 1.0):
        omega = math.pi / t
        alpha = omega / t
        M = J_PITCH * alpha
        # 力臂取半车长 2.25
        F = M / (2 * 2.25)
        print(f"    t = {t:.1f} s ⇒ α = {alpha:.2f} rad/s², "
              f"M = {M:.0f} N·m, 每喷口 F = {F:.0f} N ({F/G:.0f} kgf)")
    print()
    print("  ★ 注意：这些力都很小（几百 N 量级）——")
    print("    ⇒ **调姿用的喷口可以是「小喷口」，与主推进器完全不同规格。**")

    # ---------------- 3) 真正难的地方：定位而不是旋转 ----------------
    print("\n" + "=" * 94)
    print("【3】★★ 真正难的不是「转」，是「停在正确的角度」")
    print("=" * 94)
    print("  纯力偶的角运动方程：")
    print("    θ(t) = θ0 + ω0 t + ½ α t²")
    print("  要「转到 180° 且 ω=0」，必须：")
    print("    ① 前半程加速（喷口 A）")
    print("    ② 后半程减速（喷口 B，反向）")
    print("    ③ 精确在 θ=180° 时 ω=0")
    print()
    print("  ★ 这就是「bang-bang 控制」（最省时间/最省气）：")
    print("    加速阶段 与 减速阶段 **时长相等、力偶等大反向**")
    print()
    # 计算 bang-bang 的半程时间
    F_jet = 500.0        # 单个调姿喷口推力 (N)
    r = 2.25
    M_pair = 2 * F_jet * r
    for ang_deg, label in ((180, "倒挂半圈"), (360, "飞跃整圈")):
        ang = math.radians(ang_deg)
        # bang-bang: ang = 2 * (1/2 * alpha * (t/2)^2) = alpha*t^2/4
        #   => alpha = 4*ang/t^2
        # 同时 M = J*alpha => t = sqrt(4*J*ang/M)
        t_need = math.sqrt(4 * J_PITCH * ang / M_pair)
        print(f"  {label}（{ang_deg}°，力偶 {M_pair:.0f} N·m）：")
        print(f"    所需总时间 = √(4 J θ / M) = **{t_need:.2f} s**")

    # ---------------- 4) 与腾空时间对比 ----------------
    print("\n" + "=" * 94)
    print("【4】★ 时间够不够？（这是真正的可行性判据）")
    print("=" * 94)
    print(f"  {'场景':<20}{'腾空(s)':>10}{'调姿需要(s)':>13}"
          f"{'余量':>10}{'判定':>8}")
    for ang_deg, label, T_avail in (
        (180, "倒挂半圈", 3.7),      # HUD 实测腾空
        (360, "飞跃整圈", T_fly_flat),
    ):
        ang = math.radians(ang_deg)
        t_need = math.sqrt(4 * J_PITCH * ang / M_pair)
        ok = "✓ 够" if t_need < T_avail * 0.8 else "✗ 紧"
        print(f"  {label:<20}{T_avail:>10.2f}{t_need:>13.2f}"
              f"{T_avail-t_need:>10.2f}{ok:>8}")
    print(f"\n  （假设每个调姿喷口 {F_jet:.0f} N，力臂 {r} m）")

    # ---------------- 5) 喷口布局方案 ----------------
    print("\n" + "=" * 94)
    print("【5】★ 10 个喷口的分工方案（本文推荐）")
    print("=" * 94)
    layout = [
        ("车尾主推进", 1, "纵轴前推", "加速/抬升主推力", "大（>80 kN）"),
        ("车头反推", 2, "纵轴后推", "减速、俯仰配平", "中"),
        ("车底竖推", 2, "竖直向上", "起飞抬升（问题 2）", "大"),
        ("车顶竖推", 1, "竖直向下", "倒挂脱离（问题 1）", "中"),
        ("左侧偏航", 2, "横向", "偏航力偶 + 滚转", "小（~500 N）"),
        ("右侧偏航", 2, "横向", "偏航力偶 + 滚转", "小（~500 N）"),
    ]
    print(f"  {'位置':<14}{'数量':>4}{'方向':>10}{'作用':<22}{'规格':>12}")
    total = 0
    for name, n, d, use, spec in layout:
        print(f"  {name:<14}{n:>4}{d:>10}{use:<22}{spec:>12}")
        total += n
    print(f"  {'合计':<14}{total:>4}")
    print()
    print("  ★ 三种规格必须并存，因为它们需求差 **两个数量级**：")
    print("    · 主推进 80 kN（起飞/加速）")
    print("    · 调姿 0.5 kN（滚转/俯仰）")
    print("  ⇒ 用同一套喷口既不可能（太小推不动车），也不经济（太浪费气）")

    print("\n" + "=" * 94)
    print("  ★★★ 结论")
    print("=" * 94)
    print(f"  ① **半圈（倒挂）和整圈（飞跃）都能做**，时间上够；")
    print(f"  ② **纯力偶必须成对点火**，这就是「10 个喷口」的物理必要性；")
    print(f"  ③ **滚转比俯仰省 {J_PITCH/J_ROLL:.1f} 倍角动量** ⇒ 桶滚选滚转轴最划算；")
    print(f"  ④ **调姿喷口只需几百 N**（比主推进小两个数量级）⇒ 规格必须分开；")
    print(f"  ⑤ **真正的难点是「停准」，不是「转起来」** ⇒ bang-bang 控制；")
    print(f"  ⑥ 半圈要求**姿态唯一**（±15° 就撞顶），整圈有对称余量 ⇒ 半圈更难。")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
