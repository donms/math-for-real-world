r"""W55 · **彻底定清**：倒挂段车在坡面的哪一侧、法向力朝哪、约束是什么方向。

## 我在这上面错了两次，所以单独立一个诊断脚本

| 版本 | 我写的 | 错在哪 |
|---|---|---|
| v1 | 车在**外侧**表面，$N$ 背离圆心，约束是**速度上限** | 把"外侧"的几何套错了 |
| v2 | 车在**内侧**表面，$N$ 指向圆心，约束是**速度下限** | 把"内侧"的几何套错了 |
| **v3（本脚本）** | ★ **车在坡面【上表面】、车在坡面【下方】**；$N$ 与 $mg$ **都背离圆心** | — |

## ★ 正确的几何

**"倒挂"的含义**：车**倒过来**开 —— **车顶朝地面、车底朝天空**。
坡道从地面升起、拱过顶点后变成"天花板"。
**车贴在坡面的【下侧】行驶**（即车在坡面下方，坡面在车上方）。

**在倒挂段顶点**：

| 力 | 方向（相对圆心）|
|---|---|
| 重力 $m\mathbf{g}$ | **背离圆心**（向下）|
| 坡面对车的支持力 $N$ | **背离圆心**（向下 —— 坡面在车上方，推车向下）|
| ★ 若只有这两个力 | **没有任何力指向圆心** ⇒ **车无法做圆周运动，必然脱离** |

**⇒ 这正是"必须靠外力"的地方。**

**而这个外力只能是吸附**（或轨道夹持）。**风扇把车"吸向坡面"，
在这个姿态下就是"吸向圆心"。**

## 结论

$$\text{指向圆心：} F_a \qquad\text{背离圆心：} N + mg$$

$$\Rightarrow\quad F_a - N - mg = \frac{mv^2}{R}
\quad\Rightarrow\quad \boxed{N = F_a - mg - \frac{mv^2}{R}}$$

$$\boxed{N \ge 0 \iff F_a \ge mg + \frac{mv^2}{R} = m\left(g + \frac{v^2}{R}\right)}$$

**⇒ 约束是【吸附力的下限】，并且 $\lambda$ 随速度平方增长。**

**★ 不是"速度上限"，也不是"速度下限" —— 是"吸附力必须够大"。**

## 与上一版的对比

| 版本 | 约束 | 能否解释"为什么装风扇" |
|---|---|---|
| v1/v2（错）| 速度的上限/下限 | ❌ 解释不了（纯速度就能倒挂） |
| **v3（对）** | ★ **$F_a \ge m(g + v^2/R)$** | ✅ **完全解释**：没有吸附，$N$ 恒为负，**车根本贴不住** |
"""
from __future__ import annotations

import math

g = 9.81


def main() -> int:
    print("=" * 88)
    print("  W55 · 倒挂段：正确的力平衡")
    print("=" * 88)
    print("\n  几何：倒挂 = 车顶朝地、车底朝天；车贴在坡面【下侧】")
    print("        顶点处：坡面在车【上方】，圆心在车【下方】")
    print("\n  力的方向（取指向圆心为正向）：")
    print("    · 重力  mg   —— 向下 = 【背离圆心】  ⇒ 负")
    print("    · 支持力 N   —— 坡面在车上方，推车向下 = 【背离圆心】 ⇒ 负")
    print("    · 吸附  Fa   —— 把车吸向坡面 = 【指向圆心】 ⇒ 正")
    print("\n  ⇒ Fa − N − mg = m v²/R")
    print("  ⇒ N = Fa − mg − m v²/R")
    print("  ⇒ N ≥ 0  ⟺  Fa ≥ m(g + v²/R)")

    m = 2000.0
    print("\n" + "=" * 88)
    print(f"  需要多大的吸附力（m = {m:,.0f} kg）？")
    print("=" * 88)
    print(f"  {'R(m)':>6}{'v(km/h)':>10}{'v²/R (m/s²)':>14}"
          f"{'Fa/mg':>9}{'Fa(N)':>12}{'Δp@4m²(kPa)':>14}")
    for R in (8, 10, 15, 20):
        for vkm in (30, 60, 90):
            v = vkm / 3.6
            a = v * v / R
            lam = (g + a) / g          # Fa/mg
            Fa = m * (g + a)
            dp = Fa / 4.0 / 1000.0     # A=4m², kPa
            print(f"  {R:>6}{vkm:>10}{a:>14.2f}{lam:>9.2f}"
                  f"{Fa:>12,.0f}{dp:>14.1f}")

    print("\n" + "=" * 88)
    print("  ★ 关键判读")
    print("=" * 88)
    print("  ① 即使 v → 0，仍需 Fa ≥ mg —— 吸附【永远不可省】；")
    print("  ② Fa 随 v² 增长：速度翻倍，所需吸附力的『速度部分』翻两番；")
    print("  ③ 取 R=10m、v=60km/h：Fa ≈ 2.83 mg，即需约 2.8 倍车重的吸附力；")
    print("     若 A=4 m²，需要约 13.9 kPa 压差 ≈ 0.14 atm —— 与工业风机同一量级；")
    print("  ④ 若取公布的『横向加速度 > 2g』作参照，λ≈2 时：")
    vmax = math.sqrt((2.0 - 1.0) * g * 10) * 3.6
    print(f"     R=10m 下 λ=2 能支持的最高车速 ≈ {vmax:.1f} km/h"
          f"（因为 Fa/mg = 1 + v²/(gR) ⟹ v = √((λ−1)gR)）")
    print()
    print("  ★★★ 修正记录：我前两版把『车在坡面哪一侧』搞错了两次，")
    print("     一次得到『速度上限』、一次得到『速度下限』，**都错**。")
    print("     正确结论是【吸附力的下限】，且是速度的平方函数。")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
