r"""W47 · 数据模块（**唯一取数入口**）。

## 设计原则（都是本期的血泪）

### 1. PDF 抽取结果**不直接进模型**，先与"已核验常量表"对账

本期抽取 PDF 时踩了三个坑，**每一个都是静默错误**：
* **列序按位置取** ⇒ 年份整体错位（表格是 2021/2020/2019 降序）；
* **把 `广靖高速`（北接线）当成 `江阴大桥`（本体）** ⇒
  车均收入只有 10.4 元，低于客车一类收费 25 元；
* 临时目录路径少一层 ⇒ 全部年份"未找到"。

⇒ 所以：**抽取脚本负责"拿到数"，本模块负责"判断这个数可不可信"**。
两者对不上就报错，而不是悄悄用一个错的值。

### 2. 每个数字都要能回答三个问题

* **从哪来**（`source`：文件名 + 页码）
* 是**实测**还是**推断**（`kind`：`measured` / `inferred`）
* **可信度**（`quality`：`A` 原件印刷值 / `B` 由原件派生 / `C` 推断）

### 3. 异常必须显式暴露

* **2021 年收入有两处口径**（4,441.70 vs 3,322.15 千元/日）⇒ 都保留，标 `conflict`；
* **2024/2025 大桥量是推断** ⇒ 返回**区间**，绝不返回单点；
* 所有"算出来的比值"都要过**合理性检查**（如车均收入 vs 收费标准）。

## 用法

    from w47_data import load, BRIDGE, SHOCKS, OPENING, COST, PEERS

    $PY w47_data.py            # 自检 + 打印
    $PY w47_data.py --json     # 落盘汇总
"""
