# ══════════════════════════════════════════════════════════════════════
def check() -> list[str]:
    r"""返回问题列表（空 = 全部通过）。

    检查项（每一条都对应本期踩过的一个坑）：
    1. 客车 + 货车 == 合计（列对齐检验）；
    2. 客车占比与 PDF 印刷值一致（列对齐的**独立**证据）；
    3. 车均收入落在合理区间（识别"抓错行"）；
    4. 推断值必须给区间，不能是标量。
    """
    bad: list[str] = []

    # 1 + 3
    print("  ── 江阴大桥（实测）──")
    print(f"     {'年':<6}{'客+货':>9}{'合计':>9}{'一致':>6}"
          f"{'客车占比':>10}{'车均(元)':>10}{'合理':>6}")
    printed = {2019: 0.7634, 2020: 0.7497, 2021: 0.7276,   # PDF 印刷值
               2022: 0.6844, 2023: 0.7513}
    for y, d in sorted(BRIDGE.items()):
        s = d["客车"] + d["货车"]
        ok1 = (s == d["合计"])
        share = d["客车"] / d["合计"]
        per = d["日均收入_千元"] * 1000 / d["合计"]
        ok2 = abs(share - printed[y]) < 0.0002
        # 客车一类 25 元、货车计重 ⇒ 车均应 >= 25（实测区间 28–51）
        ok3 = 25.0 <= per <= 60.0
        print(f"     {y:<6}{s:>9,}{d['合计']:>9,}"
              f"{('v' if ok1 else 'X'):>6}{share:>10.2%}"
              f"{per:>10.2f}{('v' if ok3 else 'X'):>6}")
        if not ok1:
            bad.append(f"{y}: 客车+货车({s}) != 合计({d['合计']})")
        if not ok2:
            bad.append(f"{y}: 客车占比 {share:.4%} != 印刷值 {printed[y]:.4%}")
        if not ok3:
            bad.append(f"{y}: 车均收入 {per:.2f} 元不在 [25, 60] ⇒ 疑似抓错行")

    print("\n  ── 2024/2025（推断）──")
    print(f"     比值区间 [{RATIO_LO:.4f}, {RATIO_HI:.4f}]"
          f"（2022: {_RATIO[2022]:.4f}, 2023: {_RATIO[2023]:.4f}）")
    for y, d in sorted(INFERRED.items()):
        lo, hi = d["合计区间"]
        width = (hi - lo) / d["合计中点"]
        print(f"     {y}: 北接线 {d['北接线实测']:,} ⇒ 大桥 [{lo:,.0f}, {hi:,.0f}]"
              f"  区间宽 {width:.2%}")
        if hi <= lo:
            bad.append(f"{y}: 推断值是标量，必须给区间")
        if width > 0.10:
            bad.append(f"{y}: 推断区间宽 {width:.1%} > 10%，过宽")

    print("\n  ── 2021 收入口径冲突（**保留两个值**）──")
    cf = BRIDGE[2021]["conflict"]
    print(f"     募集说明书 {BRIDGE[2021]['日均收入_千元']:,.2f}  vs  "
          f"2022年报 {cf['日均收入_千元']:,.2f}"
          f"  差 {abs(BRIDGE[2021]['日均收入_千元'] - cf['日均收入_千元']) / cf['日均收入_千元']:.1%}")
    print(f"     ⇒ {cf['_说明']}")

    print("\n  ── 2020 免收通行费验算 ──")
    v = SHOCKS["2020免收通行费"]["_验算"]
    print(f"     {v['2020收入_千元每日']:,.2f} ÷ (1−{SHOCKS['2020免收通行费']['占比']:.4f})"
          f" = {v['归一化到全年']:,.2f}  vs 2019 {v['2019收入_千元每日']:,.2f}"
          f"  偏差 {v['相对偏差']:.2%}")
    if v["相对偏差"] > 0.01:
        bad.append("2020 免收验算偏差 > 1%")

    print("\n  ── 货车不可分流的硬约束 ──")
    shares = [d["货车"] / d["合计"] for d in BRIDGE.values()]
    print(f"     货车占比 {min(shares):.2%} – {max(shares):.2%}"
          f"（均值 {sum(shares)/len(shares):.2%}）")
    print("     隧道全时段禁货 ⇒ 这部分**无法被分流**")

    print("\n  ── 内部一致性检验（洞察 4）──")
    obs = OPENING
    d_down = -obs["大桥变化_官方"]
    phi = sum(shares) / len(shares)
    implied_s = d_down / (1 - phi)
    print(f"     大桥降幅 {d_down:.2%}，货车占比 {phi:.2%}")
    print(f"     ⇒ 隐含客车分流率 ≈ {d_down:.4f} / (1−{phi:.4f}) = **{implied_s:.2%}**")
    print(f"     隧道观测占比 = {obs['隧道_万辆']}/{obs['通道日均_万辆']}"
          f" = {obs['隧道_万辆']/obs['通道日均_万辆']:.2%}"
          f"（官方称高峰约 {obs['隧道高峰占比']:.0%}）")
    if not (0.10 <= implied_s <= 0.40):
        bad.append(f"客车分流率 {implied_s:.1%} 落在 [10%, 40%] 之外，需复核")

    return bad


def load() -> dict:
    r"""统一返回所有数据（供各问脚本使用）。"""
    return {"bridge": BRIDGE, "inferred": INFERRED, "shocks": SHOCKS,
            "opening": OPENING, "cost": COST, "peers": PEERS,
            "ratio_bounds": (RATIO_LO, RATIO_HI),
            "north_approach": _BEI, "south_approach": _NAN}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--json", action="store_true")
    args = ap.parse_args()

    print("=" * 92)
    print("  W47 数据模块自检")
    print("=" * 92)
    bad = check()

    print(f"\n{'='*92}")
    if bad:
        print(f"  [X] {len(bad)} 项未通过：")
        for b in bad:
            print(f"     · {b}")
    else:
        print("  [OK] 全部通过")

    if args.json:
        p = RES / "q1_数据模块汇总.json"
        p.write_text(json.dumps(
            {"bridge": {str(k): v for k, v in BRIDGE.items()},
             "inferred": {str(k): v for k, v in INFERRED.items()},
             "shocks": SHOCKS, "opening": OPENING, "cost": COST,
             "peers": {k: ({str(a): b for a, b in v.items()}
                           if isinstance(v, dict) and k != "source"
                           else v)
                       for k, v in PEERS.items()},
             "ratio_bounds": [RATIO_LO, RATIO_HI],
             "north_approach": {str(k): v for k, v in _BEI.items()},
             "south_approach": {str(k): v for k, v in _NAN.items()},
             "selfcheck_passed": not bad},
            ensure_ascii=False, indent=2), encoding="utf-8")
        print(f"  -> {p.relative_to(ROOT)}")
    return 0 if not bad else 1


if __name__ == "__main__":
    raise SystemExit(main())
