r"""W54 · 问题 2：**钱去哪了**（分层贡献分解 + 达标路径反解）。

## 对应模型文档

`models/02_钱去哪了.md` —— 该文档 §2.8 已**预先写下预期结论**，
本脚本独立算出结果并与预期对照。

## 本脚本回答

1. **物业费单项**是否够本？（已由问题 1 定位，这里给出单位口径）
2. **单位成本**是多少？与住宅名义单价 4.91 差多少？
3. **分业态净贡献**：住宅 / 商业 / 地库，谁补贴谁？
   ★ 分摊规则必须显式（主用**按面积**，附**按收入**做敏感性）。
4. 要达**万物云住宅业态 11.7%** 的毛利率，
   ① 提单价要多少？② 压成本要压到多少？
5. 与业委会诉求（**降价 51.2%**）对比。

## ★ 两条硬约束（模型文档 §2.3）

* **地库只承担自己的 68 162.53**，不参与支出表分摊；
* **管理费与税金不再二次按面积分摊**（它们本身有计费基数）。

## ★ 处理 2 600 的方式（模型文档 §2.5）

问题 1 定位到"收入侧多 2 600"，来源不明
⇒ 本脚本把它**单列为「未识别收入」**，不塞进任何单元，
使 `Σ净贡献 + 未识别 − 管理费 − 税金 == 表给利润`。
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
EP = ROOT / "episodes" / "2026-W54"
OUT = EP / "results"
OUT.mkdir(parents=True, exist_ok=True)

# ================= 定稿口径（来自问题 1 的检验结果） =================
D = {
    "住宅面积": 276866.55, "商业面积": 5422.84,
    "收费面积": 282289.39,
    "住宅单价": 4.91, "商业单价": 13.55,
    "I_住宅": 1359414.76, "I_商业": 73479.48,
    "I_物业费": 1432894.24,
    "I_停车": 148500.00,
    "I_合计表给": 1583994.24,
    "E_支出表月合计": 1508798.21,
    "E_地库": 68162.53,
    "E_合计": 1576960.74,
    "管理费": 128409.79, "税金": 96290.49,
    "合计行_直接成本基数": 1284097.92,
    "利润_表给": 4433.50,
    "户数": 1867,
    "车位数": 2475,
    # ---- 行业锚点 ----
    "万物云住宅毛利率": 0.117,
    "行业毛利率下限": 0.05, "行业毛利率上限": 0.20,
    "20城均价": 2.72,
    "业委会诉求单价": 2.398,
}

UNIDENTIFIED = 2600.00     # ★ 问题 1 定位到的「收入侧未识别」金额


def main() -> int:
    print("=" * 94)
    print("  W54 · 问题 2：钱去哪了")
    print("=" * 94)

    # ---------------- 一、两个结构性事实 ----------------
    print("\n-- 一、两个结构性事实 --")
    gap = D["I_物业费"] - D["E_合计"]
    print(f"  ① 物业费小计 − 支出 = {D['I_物业费']:,.2f} − "
          f"{D['E_合计']:,.2f} = **{gap:+,.2f} 元/月**"
          f"（年 {gap*12:+,.2f}）")
    ng = D["I_停车"] - D["E_地库"]
    print(f"  ② 停车费 − 地库支出 = {D['I_停车']:,.2f} − "
          f"{D['E_地库']:,.2f} = **{ng:+,.2f} 元/月**"
          f"（年 {ng*12:+,.2f}）")
    print(f"  ⇒ 两者相加 = {gap+ng:+,.2f}；表给利润 "
          f"{D['利润_表给']:,.2f}"
          f"　差 {gap+ng-D['利润_表给']:+,.2f}"
          f"（= 未识别 {UNIDENTIFIED:,.0f}）")

    # ---------------- 二、单位口径 ----------------
    print(f"\n{'='*94}")
    print("  二、单位口径（**必须用收费面积，不能用总建面**）")
    print(f"{'='*94}")
    A = D["收费面积"]
    uc = D["E_合计"] / A
    uf = D["I_物业费"] / A
    ua = D["I_合计表给"] / A
    up = D["I_停车"] / A
    print(f"  收费面积 {A:,.2f} ㎡（住宅 {D['住宅面积']:,.2f} + "
          f"商业 {D['商业面积']:,.2f}）")
    print(f"  单位成本 E_all/A      = {uc:>8.4f} 元/㎡·月")
    print(f"  单位物业费收入 I_f/A  = {uf:>8.4f}")
    print(f"  单位停车收入 I_p/A    = {up:>8.4f}")
    print(f"  单位总收入 I_all/A    = {ua:>8.4f}")
    print(f"  ⇒ ★ **物业费单项单位差额** = {uf-uc:+.4f} 元/㎡·月"
          f"（占收费 {(uf-uc)/uf*100:+.2f}%）")
    print(f"  ⇒ ★ **含停车后单位差额** = {ua-uc:+.4f} 元/㎡·月"
          f"（占收入 {(ua-uc)/ua*100:+.2f}%）")
    print(f"  ⇒ 单位缺口（成本 − 住宅名义单价 4.91）= "
          f"{uc-D['住宅单价']:+.4f} 元/㎡·月")
    print(f"     年缺口 = {(uc-D['住宅单价'])*A*12:+,.0f} 元")
    print(f"\n  ★ 反例警示：若误用**总建筑面积 41.54 万㎡**，"
          f"单位成本会变成 {D['E_合计']/415400:.4f} —— **结论反向**")

    # ---------------- 三、分业态净贡献 ----------------
    print(f"\n{'='*94}")
    print("  三、分业态净贡献（★ 分摊规则显式写出）")
    print(f"{'='*94}")
    direct = D["E_支出表月合计"] - D["管理费"] - D["税金"]
    print(f"  直接成本 = 支出表月合计 − 管理费 − 税金")
    print(f"           = {D['E_支出表月合计']:,.2f} − {D['管理费']:,.2f} − "
          f"{D['税金']:,.2f} = **{direct:,.2f}**")
    print(f"  ★ 注意：它恰等于问题 1 里的「合计行」"
          f"{D['合计行_直接成本基数']:,.2f}（差 "
          f"{direct-D['合计行_直接成本基数']:+,.2f}）")
    print(f"     ⇒ **「合计行」确实是直接成本基数** —— 两个独立口径互证 ✓")

    rules = {
        "按面积（主）": (D["住宅面积"] / A, D["商业面积"] / A),
        "按收入（敏感性）": (D["I_住宅"] / D["I_物业费"],
                      D["I_商业"] / D["I_物业费"]),
    }
    all_res: dict = {}
    for rname, (wr, wc) in rules.items():
        print(f"\n  ---- 分摊规则：{rname} ----")
        print(f"  权重：住宅 {wr*100:.2f}%　商业 {wc*100:.2f}%")
        units = [
            ("住宅", D["I_住宅"], direct * wr),
            ("商业", D["I_商业"], direct * wc),
            ("地库", D["I_停车"], D["E_地库"]),
        ]
        print(f"  {'单元':<6}{'收入/月':>14}{'直接成本/月':>14}"
              f"{'净贡献/月':>14}{'净贡献率':>10}{'净贡献/年':>15}")
        rows = []
        tot_nc = 0.0
        for nm, inc, cost in units:
            nc = inc - cost
            tot_nc += nc
            rate = nc / inc if inc else 0.0
            rows.append({"单元": nm, "收入": inc, "直接成本": cost,
                         "净贡献": nc, "净贡献率": rate})
            print(f"  {nm:<6}{inc:>14,.0f}{cost:>14,.0f}{nc:>14,.0f}"
                  f"{rate*100:>9.2f}%{nc*12:>15,.0f}")
        print(f"  {'合计':<6}{sum(r['收入'] for r in rows):>14,.0f}"
              f"{sum(r['直接成本'] for r in rows):>14,.0f}"
              f"{tot_nc:>14,.0f}"
              f"{tot_nc/sum(r['收入'] for r in rows)*100:>9.2f}%"
              f"{tot_nc*12:>15,.0f}")
        # 恒等式自检
        # ★★ 正确的关系（我前两版都写反了，记下来）：
        #   (a) Σ净贡献 = 收入合计 − 直接成本合计
        #   (b) Σ净贡献 − 管理费 − 税金 = **收入 − 支出** = 7 033.50
        #   (c) ★ **表给利润 = (b) − 2 600**  ← 表给利润**比 (b) 少 2 600**
        #       即那 2 600 是**表在净额上又扣掉的一笔**
        #       （问题 1 已证它不在支出明细里）⇒ 属表外扣减，来源不明。
        chk_b = tot_nc - D["管理费"] - D["税金"]
        chk_c = chk_b - UNIDENTIFIED
        print("  ★ 恒等式自检（三条）：")
        inc_sum_all = sum(r["收入"] for r in rows)
        cost_sum_all = sum(r["直接成本"] for r in rows)
        print(f"     (a) Σ净贡献 = 收入 − 直接成本")
        print(f"         {tot_nc:,.2f} vs {inc_sum_all:,.2f} − "
              f"{cost_sum_all:,.2f} = {inc_sum_all-cost_sum_all:,.2f}"
              f"　{'✓' if abs(tot_nc-(inc_sum_all-cost_sum_all)) <= 0.02 else '✗'}")
        print(f"     (b) Σ净贡献 − 管理费 − 税金 = 收入 − 支出")
        print(f"         {chk_b:,.2f} vs "
              f"{D['I_合计表给']-D['E_合计']:,.2f}"
              f"　{'✓' if abs(chk_b-(D['I_合计表给']-D['E_合计'])) <= 0.02 else '✗'}")
        print(f"     (c) ★ 表给利润 = (b) − {UNIDENTIFIED:,.0f}")
        print(f"         {chk_c:,.2f} vs 表给 {D['利润_表给']:,.2f}"
              f"　{'✓ 吻合' if abs(chk_c-D['利润_表给']) <= 0.02 else '✗'}")
        print(f"         ⇒ ★★ **即：表在净额上又多扣了 {UNIDENTIFIED:,.0f} 元/月**"
              f"（问题 1 已证它不在支出明细里）")
        all_res[rname] = {"权重": {"住宅": wr, "商业": wc},
                          "单元": rows, "Σ净贡献": tot_nc,
                          "净额_收入减支出": chk_b,
                          "表给利润_校验": chk_c,
                          "校验通过": abs(chk_c - D["利润_表给"]) <= 0.02}

    # 主规则下的结论
    main_res = all_res["按面积（主）"]
    print(f"\n  ★★ 主规则（按面积）下的结论：")
    for r in main_res["单元"]:
        print(f"     {r['单元']:<4} 净贡献 {r['净贡献']:>12,.0f} 元/月"
              f"（率 {r['净贡献率']*100:>6.2f}%）")
    resid = next(r for r in main_res["单元"] if r["单元"] == "住宅")
    others = sum(r["净贡献"] for r in main_res["单元"]
                 if r["单元"] != "住宅")
    print(f"  ⇒ ★★ 住宅 **{resid['净贡献']:,.0f}**，商业+地库 "
          f"**{others:,.0f}** 元/月")
    print(f"  ⇒ ★ 住宅**并不是在亏**（净贡献 "
          f"{resid['净贡献']:,.0f} 元/月、率 "
          f"{resid['净贡献率']*100:.2f}%），")
    print(f"     但它的**贡献率远低于另两个单元** —— 差在「单位面积的收入」上：")
    ur = D["I_住宅"] / D["住宅面积"]
    uc2 = D["I_商业"] / D["商业面积"]
    up2 = D["I_停车"] / D["车位数"]
    print(f"       住宅单价 {ur:.2f} 元/㎡·月"
          f"｜商业 {uc2:.2f}（是住宅 {uc2/ur:.2f} 倍）")
    print(f"     ⇒ 而直接成本**按面积分摊** ⇒ 商业用 {D['商业面积']/A*100:.2f}% "
          f"的面积，贡献了 {next(r['净贡献'] for r in main_res['单元'] if r['单元']=='商业'):,.0f} 元/月")
    print(f"  ⇒ ★★ **准确的说法（我前两版都说反了）：**")
    print(f"     · 住宅**不是在亏**：净贡献 {resid['净贡献']:,.0f} 元/月、"
          f"率 {resid['净贡献率']*100:.2f}%")
    print(f"     · 但它的**贡献率只有商业的 "
          f"{resid['净贡献率']/next(r['净贡献率'] for r in main_res['单元'] if r['单元']=='商业')*100:.0f}%**"
          f"，原因是**单位面积收入太低**：")
    print(f"       住宅 {ur:.2f} 元/㎡·月　vs　商业 {uc2:.2f}"
          f"（{uc2/ur:.2f} 倍）")
    print(f"     · 而直接成本**按面积分摊**（住宅占 "
          f"{D['住宅面积']/A*100:.1f}% 的面积）")
    print(f"  ⇒ ★★ **所以正确的表述是：**")
    print(f"     **住宅以 4.91 元的低单价承担了 98% 面积的看护成本，"
          f"贡献率被压到 7.35%；**")
    print("     **商业与地库是「高单价/零面积」单元，"
          f"合计贡献 {others:,.0f} 元/月，把总账拉回正数。**")
    print("  ⇒ ★ 换句话说：**不是「商业补贴住宅」，"
          "而是「住宅自己贡献太薄，全靠商业与停车把总账撑住」**。")

    # ---------------- 四、达标路径 ----------------
    print(f"\n{'='*94}")
    print("  四、达标路径：要达到万物云住宅业态 11.7% 的毛利率")
    print(f"{'='*94}")
    pi = D["万物云住宅毛利率"]
    E, Iall = D["E_合计"], D["I_合计表给"]
    print(f"  目标经营利润率 π* = **{pi*100:.1f}%**（万物云住宅业态，"
          f"全行业唯一披露）")
    print(f"  行业平均毛利率区间 **{D['行业毛利率下限']*100:.0f}%–"
          f"{D['行业毛利率上限']*100:.0f}%**")

    # 路径①：提单价
    need_I = E / (1 - pi)
    need_p = (need_I - D["I_商业"] - D["I_停车"]) / D["住宅面积"]
    print(f"\n  -- 路径 ①：提单价（成本不变）--")
    print(f"     需总收入 I* = E/(1−π*) = {E:,.2f} / {1-pi} = "
          f"**{need_I:,.2f} 元/月**")
    print(f"     实际收入 {Iall:,.2f} ⇒ 差 **{need_I-Iall:+,.2f} 元/月**"
          f"（年 {(need_I-Iall)*12/1e4:+,.1f} 万元）")
    print(f"     住宅物业费需从 {D['住宅单价']:.2f} 提到 "
          f"**{need_p:.3f} 元/㎡·月**")
    print(f"     ⇒ **+{(need_p/D['住宅单价']-1)*100:.1f}%**")

    # 路径②：压成本
    need_E = Iall * (1 - pi)
    print(f"\n  -- 路径 ②：压成本（收入不变）--")
    print(f"     需总成本 E* = I_all(1−π*) = {Iall:,.2f} × {1-pi} = "
          f"**{need_E:,.2f} 元/月**")
    print(f"     实际成本 {E:,.2f} ⇒ 需压 **{need_E-E:+,.2f} 元/月**"
          f"（年 {(need_E-E)*12/1e4:+,.1f} 万元）")
    print(f"     ⇒ **{(1-need_E/E)*100:.1f}%**")
    print(f"     ★ 参照：人员费用占支出 "
          f"{1019116.76/E*100:.1f}% ⇒ 要压 {(E-need_E)/1019116.76*100:.0f}% "
          f"的人员费用")

    # ---------------- 五、与业委会诉求对比 ----------------
    print(f"\n{'='*94}")
    print("  五、与业委会诉求对比")
    print(f"{'='*94}")
    dem = D["业委会诉求单价"]
    drop = (1 - dem / D["住宅单价"]) * 100
    print(f"  业委会诉求：{D['住宅单价']:.3f} → **{dem:.3f} 元/㎡·月**"
          f"（**降 {drop:.1f}%**）")
    print(f"  达标路径 ① ：{D['住宅单价']:.3f} → **{need_p:.3f}**"
          f"（**升 {(need_p/D['住宅单价']-1)*100:.1f}%**）")
    print(f"  ⇒ ★★ **两条方向完全相反**")
    # 按诉求价算会怎样
    inc_dem = D["住宅面积"] * dem + D["I_商业"] + D["I_停车"]
    prof_dem = inc_dem - E
    print(f"\n  若真按诉求价执行：")
    print(f"     住宅物业费收入 {D['住宅面积']*dem:,.2f}"
          f"（现 {D['I_住宅']:,.2f} ⇒ 少 "
          f"{D['I_住宅']-D['住宅面积']*dem:,.2f} 元/月）")
    print(f"     总收入 {inc_dem:,.2f} − 支出 {E:,.2f} = "
          f"**{prof_dem:+,.2f} 元/月**"
          f"（年 {prof_dem*12/1e4:+,.1f} 万元）")
    print(f"     ⇒ **每月亏 {abs(prof_dem):,.0f} 元**")
    print(f"     ★ 对比：物业的强制退出红线是"
          f"「连续两年收支不平衡」⇒ **第一年就触发**")

    # ---------------- 落盘 ----------------
    res = {
        "_来源": "问题 1 的定稿口径（models/01_账目体检.md §1.5）",
        "结构性事实": {
            "物业费与支出的差额": gap,
            "停车与地库的差额": ng,
            "未识别收入": UNIDENTIFIED,
            "利润_表给": D["利润_表给"],
            "利润_计算": D["I_合计表给"] - D["E_合计"],
        },
        "单位口径": {
            "收费面积": A, "单位成本": uc, "单位物业费收入": uf,
            "单位停车收入": up, "单位总收入": ua,
            "物业费单位差额": uf - uc, "含停车单位差额": ua - uc,
            "单位缺口_vs_4.91": uc - D["住宅单价"],
            "_反例_用总建面": D["E_合计"] / 415400,
        },
        "分摊规则结果": all_res,
        "达标路径": {
            "目标利润率": pi,
            "路径1_提单价": {"需总收入": need_I, "需单价": need_p,
                        "变化率": need_p / D["住宅单价"] - 1},
            "路径2_压成本": {"需总成本": need_E,
                        "需压金额": need_E - E,
                        "变化率": 1 - need_E / E,
                        "占人员费用比例": (E - need_E) / 1019116.76},
        },
        "业委会诉求": {
            "诉求单价": dem, "降幅": drop,
            "执行后月利润": prof_dem, "执行后年利润": prof_dem * 12,
            "结论": "第一年即触发物业的强制退出红线",
        },
        "_诚实性": [
            "分摊规则是选择而非事实 ⇒ 已给按面积与按收入两套结果",
            "净贡献率 ≠ 毛利率（未扣表外总部费用）",
            "11.7% 是行业参考值，非本小区应有水平",
            f"{UNIDENTIFIED:,.0f} 元未识别收入单列，不参与分摊",
        ],
    }
    p = OUT / "q2_钱去哪了.json"
    p.write_text(json.dumps(res, ensure_ascii=False, indent=2),
                 encoding="utf-8")
