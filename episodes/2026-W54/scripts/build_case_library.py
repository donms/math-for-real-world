def main() -> int:
    print("=" * 92)
    print("  W54 案例库")
    print("=" * 92)
    cols = ["小区", "城市", "物业", "代码", "户数", "建面_万m2",
            "收费面积_万m2", "原单价", "诉求单价", "保本成本", "降幅",
            "原因", "时间", "来源", "数据性质"]
    p = OUT / "案例库.csv"
    with p.open("w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols, extrasaction="ignore")
        w.writeheader()
        for c in CASES:
            w.writerow(c)
    print(f"  [落盘] {p}  （{len(CASES)} 条）\n")

    have_hh = [c for c in CASES if c.get("户数")]
    have_area = [c for c in CASES if c.get("建面_万m2")]
    have_price = [c for c in CASES if c.get("原单价")]
    have_cost = [c for c in CASES if c.get("保本成本")]
    print("  字段覆盖度（这是「能不能做规模分析」的前提）：")
    print(f"    有户数   {len(have_hh):>3}/{len(CASES)}")
    print(f"    有建面   {len(have_area):>3}/{len(CASES)}")
    print(f"    有原单价 {len(have_price):>3}/{len(CASES)}")
    print(f"    有保本成本 {len(have_cost):>3}/{len(CASES)}")
    print()
    print(f"  -- 同时有「户数 + 单价」的案例（可做规模-单价分析）--")
    print(f"  {'小区':<22}{'城市':<10}{'户数':>7}{'单价':>7}"
          f"{'保本成本':>9}")
    for c in have_hh:
        if not c.get("原单价"):
            continue
        print(f"  {c['小区'][:20]:<22}{c['城市'][:8]:<10}"
              f"{c['户数']:>7}{c['原单价']:>7.2f}"
              f"{(c.get('保本成本') or float('nan')):>9.2f}")

    json.dump(CASES, (OUT / "案例库.json").open("w", encoding="utf-8"),
              ensure_ascii=False, indent=1)
    print(f"\n  [落盘] {OUT / '案例库.json'}")
    return 0


