#!/usr/bin/env python -X utf8
# -*- coding: utf-8 -*-
r"""W54 · 问题 3：**降到多少会崩**（保本单价 + 保本收缴率 + 退出红线 + 敏感性）。

## 对应模型文档

`models/03_降到多少会崩.md` —— §3.6 已**预先写下预期结论**，
本脚本独立算出并对照。

## ★ 本问的核心洞察

**两个「保本」是同一个量**：

$$\rho^* \cdot p_0 = p^*$$

因为"总收入 = 住宅单价 × 面积 × 收缴率 + 商业 + 停车"
⇒ 把 $p$ 换成 $p_0\rho$ 是同一个式子。

**⇒ 本脚本把这个恒等式作为自检**（不通过就说明推导错了）。

## 退出红线的判据（**用公开来源，不自创**）

| 来源 | 判据 |
|---|---|
| 中指研究院（彭雨）| **85% 是单个项目的盈亏平衡线**；< 60% 大概率深度亏损 |
| 某物企内部强制退出制度 | 连续两年收支不平衡 / 连续两个缴费期收缴率 < 50% |

## 口径说明

* **口径 A（主）**：只有**住宅物业费**按收缴率打折（商业与停车视为独立、照收）；
* **口径 B（对照）**：**全部收入**都按收缴率打折（更保守）。
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
EP = ROOT / "episodes" / "2026-W54"
OUT = EP / "results"
OUT.mkdir(parents=True, exist_ok=True)

D = {
    "住宅面积": 276866.55, "商业面积": 5422.84, "收费面积": 282289.39,
    "住宅单价": 4.91, "商业单价": 13.55,
    "I_住宅": 1359414.76, "I_商业": 73479.48, "I_物业费": 1432894.24,
    "I_停车": 148500.00, "I_合计": 1583994.24,
    "E": 1576960.74,
    "支出明细": {"人员费用": 1019116.76, "公共设施维护费": 107790.00,
             "清洁卫生费": 88085.83, "绿化养护费": 36405.33,
             "秩序维护费": 9400.00, "行政办公费": 22200.00,
             "固定资产折旧": 3500.00, "公众责任险费": 1100.00},
    "管理费": 128409.79, "税金": 96290.49, "地库": 68162.53,
    # 行业锚点
    "行业保本线": 0.85, "深度亏损线": 0.60, "强制退出线": 0.50,
    "500强均值": 0.71, "上市物企": 0.78,
}


def main() -> int:
    print("=" * 94)
    print("  W54 · 问题 3：降到多少会崩")
    print("=" * 94)
    A_r, A_t = D["住宅面积"], D["收费面积"]
    E, Ic, Ip, Ir = D["E"], D["I_商业"], D["I_停车"], D["I_住宅"]
    p0, I0 = D["住宅单价"], D["I_合计"]

    # ---------------- 一、保本单价 ----------------
    print(f"\n-- 1. 保本单价 p*（收缴率 100%）--")
    print(f"  要求：p·A_r + I_c + I_p = E")
    p_star = (E - Ic - Ip) / A_r
    print(f"  ⇒ p* = (E − I_c − I_p) / A_r")
    print(f"       = ({E:,.2f} − {Ic:,.2f} − {Ip:,.2f}) / {A_r:,.2f}")
    print(f"       = {E-Ic-Ip:,.2f} / {A_r:,.2f} = **{p_star:.4f} 元/㎡·月**")
    print(f"  现行单价 p0 = {p0}")
    print(f"  ⇒ 差额 **{p0-p_star:+.4f} 元**（现行比保本高 "
          f"{(p0/p_star-1)*100:+.3f}%）")
    print(f"  ★ 即：**现行单价已经贴在保本线上，几乎没有空间**")

    # ---------------- 二、保本收缴率（两个口径） ----------------
    print(f"\n{'='*94}")
    print("  2. ★★ 保本收缴率 ρ*（两个口径）")
    print(f"{'='*94}")
    rho_A = (E - Ic - Ip) / Ir
    rho_B = E / I0
    print(f"  -- 口径 A（主）：只有**住宅物业费**按 ρ 打折 --")
    print(f"     ρ*_A = (E − I_c − I_p) / I_r = {E-Ic-Ip:,.2f} / "
          f"{Ir:,.2f} = **{rho_A:.4f}（{rho_A*100:.2f}%）**")
    print(f"  -- 口径 B（对照）：**全部收入**按 ρ 打折 --")
    print(f"     ρ*_B = E / I_合计 = {E:,.2f} / {I0:,.2f} = "
          f"**{rho_B:.4f}（{rho_B*100:.2f}%）**")
    print(f"\n  ★★ 恒等式自检：ρ*_A × p0 应 = p*")
    lhs = rho_A * p0
    print(f"     {rho_A:.6f} × {p0} = **{lhs:.6f}**　vs p* = "
          f"{p_star:.6f}　差 {lhs-p_star:+.2e}"
          f"　{'✓ 通过' if abs(lhs-p_star) < 1e-6 else '✗ 不通过'}")
    print(f"     （容差 1e-6；浮点乘除的相对误差约 1e-12）")
    print("     ⇒ ★ **两个「保本」是同一个量的两种表达** —— 推导自洽 ✓")

    print(f"\n  ★★ 与行业基准对比：")
    print(f"  {'基准':<28}{'值':>9}{'本案 ρ*_A − 基准':>18}")
    for nm, v in (("行业保本线（中指）", D["行业保本线"]),
                  ("500 强平均收缴率", D["500强均值"]),
                  ("上市物企平均", D["上市物企"]),
                  ("深度亏损线（中指 <60%）", D["深度亏损线"]),
                  ("强制退出线（<50%）", D["强制退出线"])):
        print(f"  {nm:<28}{v*100:>8.1f}%{(rho_A-v)*100:>+17.1f}pp")
    print(f"\n  ⇒ ★★★ **本案的保本收缴率 {rho_A*100:.2f}% 比行业保本线 "
          f"{D['行业保本线']*100:.0f}% 还高 "
          f"{(rho_A-D['行业保本线'])*100:.2f} 个百分点**")
    print(f"     ⇒ **它比行业平均项目更脆弱** —— 这才是要报的结论。")

    # ---------------- 三、利润随收缴率的曲线 ----------------
    print(f"\n{'='*94}")
    print("  3. ★★ 利润随收缴率的曲线（口径 A：只有住宅打折）")
    print(f"{'='*94}")
    print(f"  Π(ρ) = ρ·I_r + I_c + I_p − E")
    print(f"  斜率 = I_r = {Ir:,.2f} 元/月"
          f" ⇒ **每降 1 个百分点，月利润减少 {Ir/100:,.2f} 元**")
    print(f"\n  {'收缴率':>8}{'实收/月':>15}{'支出/月':>15}{'月利润':>14}"
          f"{'年利润(万)':>12}  判定")
    table = []
    for pct in range(100, 49, -5):
        rho = pct / 100
        real = rho * Ir + Ic + Ip
        prof = real - E
        if prof > 0:
            v = "盈利"
        elif rho >= D["行业保本线"]:
            v = "★ 亏损（仍在行业保本线之上）"
        elif rho >= D["深度亏损线"]:
            v = "★★ 亏损（低于行业保本线）"
        else:
            v = "★★★ 深度亏损（<60%）"
        table.append({"收缴率": rho, "实收": real, "月利润": prof,
                      "年利润": prof * 12, "判定": v})
        print(f"  {pct:>7}%{real:>15,.0f}{E:>15,.0f}{prof:>14,.0f}"
              f"{prof*12/1e4:>12,.1f}  {v}")
    print(f"\n  ★ 临界（利润 = 0）：ρ = **{rho_A*100:.2f}%**")
    # 找表中由盈转亏的一档
    first_loss = next(t for t in table if t["月利润"] < 0)
    print(f"     表中首个亏损档：**{first_loss['收缴率']*100:.0f}%**"
          f" ⇒ 月亏 **{first_loss['月利润']:,.0f}**")

    # ---------------- 四、退出红线判定 ----------------
    print(f"\n{'='*94}")
    print("  4. ★★ 是否已越过物业公司的强制退出红线？")
    print(f"{'='*94}")
    print("  判据（公开来源）：")
    print(f"    ① 中指研究院：**85% 是单个项目的盈亏平衡线**；"
          f"< 60% 大概率深度亏损")
    print(f"    ② 某物企内部强制退出制度：**连续两年收支不平衡**，"
          f"或**连续两个缴费期收缴率 < 50%**")
    print(f"\n  逐条判定（假设实际收缴率 ρ 未知，给出**阈值反推**）：")
    # 连续两年收支不平衡 ⇒ 年利润为负
    rho_year = rho_A          # 一年内 收支平衡
    print(f"    · 判据①「连续两年收支不平衡」⇒ 需年利润 < 0")
    print(f"      ⇒ 触发条件：**ρ < {rho_year*100:.2f}%**（即只要不是满收）")
    print(f"    · 判据②「连续两期收缴率 < 50%」")
    print(f"      ⇒ 触发条件：**ρ < 50%**")
    print(f"\n  ★★ 结论：")
    print(f"    **本案的收支平衡点（ρ* = {rho_A*100:.2f}%）远高于 50%** ⇒")
    print(f"    **① 「连续两年收支不平衡」这条比 ② 容易触发得多**：")
    print(f"       只要实际收缴率低于 **{rho_A*100:.2f}%**（不是 50%），"
          f"就已连续亏损。")
    print(f"    ⇒ ★ **而 {rho_A*100:.2f}% 高于中指给的行业保本线 85%**，")
    print(f"       也高于 500 强平均 {D['500强均值']*100:.0f}% 与上市物企 "
          f"{D['上市物企']*100:.0f}% ⇒")
    print(f"       **它几乎必然触发退出条件 —— 只要收缴率低于行业平均。**")
    print(f"\n    ★ 反过来说：**物业宣布撤场，在表内数据上是可解释的** ——")
    print(f"      不是「不想干」，而是「按行业平均收缴率就必亏」。")

    # ---------------- 五、三参数敏感性 ----------------
    print(f"\n{'='*94}")
    print("  5. ★★ 敏感性分析：三个参数各 ±20% 对保本单价的影响")
    print(f"{'='*94}")
    base_item = D["支出明细"]["人员费用"]
    print(f"  基线：保本单价 p* = **{p_star:.4f}**；"
          f"保本收缴率 ρ* = **{rho_A*100:.2f}%**")
    print(f"\n  {'参数':<14}{'变动':>8}{'新 p*':>11}{'Δp*':>10}"
          f"{'新 ρ*':>10}{'Δρ*(pp)':>11}  说明")
    sens = []
    for nm, key, kind in (("人员费用", "人员费用", "cost"),
                          ("车位收入", "I_停车", "rev"),
                          ("商业物业费", "I_商业", "rev")):
        for d in (-0.20, 0.20):
            if kind == "cost":
                E2 = E + base_item * d
            else:
                E2 = E
            Ic2 = Ic + (D["I_商业"] * d if key == "I_商业" else 0)
            Ip2 = Ip + (Ip * d if key == "I_停车" else 0)
            p2 = (E2 - Ic2 - Ip2) / A_r
            r2 = (E2 - Ic2 - Ip2) / Ir
            eff = p2 - p_star
            sens.append({"参数": nm, "变动": d, "新保本单价": p2,
                         "新保本收缴率": r2})
            print(f"  {nm:<14}{d*100:>+7.0f}%{p2:>11.4f}{eff:>+10.4f}"
                  f"{r2*100:>9.2f}%{(r2-rho_A)*100:>+10.2f}  "
                  f"{'★ 影响最大' if nm=='人员费用' else ''}")
    # 排名
    print(f"\n  ★ 影响排序（按 |Δp*|）：")
    mx = {}
    for s in sens:
        mx[s["参数"]] = max(mx.get(s["参数"], 0),
                          abs(s["新保本单价"] - p_star))
    for nm, v in sorted(mx.items(), key=lambda x: -x[1]):
        print(f"     {nm:<14}最大 |Δp*| = {v:.4f} 元/㎡·月"
              f"（占基线 {v/p_star*100:.2f}%）")
    print(f"\n  ⇒ ★ **人员费用影响最大**（占支出 "
          f"{base_item/E*100:.1f}%，且是最大单项）")
    print(f"     ⇒ 与问题 2 的达标路径 ② 一致：压成本必须动人员费用")

    # ---------------- 落盘 ----------------
    res = {
        "_来源": "问题 1、2 的定稿口径",
        "保本单价": p_star,
        "现行单价": p0,
        "单价余量_元": p0 - p_star,
        "单价余量_百分比": p0 / p_star - 1,
        "保本收缴率_口径A_只有住宅打折": rho_A,
        "保本收缴率_口径B_全部打折": rho_B,
        "恒等式校验_ρA乘p0等于pstar": {
            "左": rho_A * p0, "右": p_star,
            "通过": abs(rho_A * p0 - p_star) < 1e-6,
        },
        "与行业基准对比_pp": {
            "行业保本线85%": (rho_A - D["行业保本线"]) * 100,
            "500强均值71%": (rho_A - D["500强均值"]) * 100,
            "上市物企78%": (rho_A - D["上市物企"]) * 100,
        },
        "利润曲线": table,
        "退出红线判定": {
            "判据1_连续两年收支不平衡": {
                "触发条件_ρ": rho_A,
                "说明": "只要实际收缴率低于保本收缴率即连续亏损",
            },
            "判据2_连续两期收缴率低于50%": {"触发条件_ρ": 0.50},
            "结论": f"本案保本收缴率 {rho_A*100:.2f}% 远高于 50%，"
                  f"也高于行业保本线 85% ⇒ 判据① 比 判据② 容易触发得多；"
                  f"只要收缴率低于行业平均，就几乎必然触发退出条件",
        },
        "敏感性": {"基线保本单价": p_star, "基线保本收缴率": rho_A,
                 "结果": sens,
                 "影响排序": sorted(mx.items(), key=lambda x: -x[1])},
        "_诚实性": [
            "ρ* 是表内隐含的收支平衡点，非实测收缴率；"
            "附件各行为应收口径，未扣欠费",
            "假设商业与停车收入不随收缴率下滑（简化）",
            "退出红线判据来自公开来源，非本小区合同条款",
            "敏感性给的是'参数变动下保本线移动'，不等于未来预测",
        ],
    }
    p = OUT / "q3_保本分析.json"
    p.write_text(json.dumps(res, ensure_ascii=False, indent=2),
                 encoding="utf-8")
    print(f"\n  [落盘] {p}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
