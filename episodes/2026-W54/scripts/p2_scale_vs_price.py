#!/usr/bin/env python -X utf8
# -*- coding: utf-8 -*-
r"""W54 · **核心检验：撤场到底跟"规模"有关，还是跟"单价"有关？**

## 为什么要做这个检验

用户提的假说是：**地块变小 ⇒ 户数少 ⇒ 固定成本分摊难 ⇒ 争端变多**。

而取证报告给出一条**必须处理的反例**（原话）：

> 大项目同样因谈崩撤场：江湾雅园（1867 户 / 41.54 万㎡ / 年入约 2000 万）、
> 连城国际（近 3800 户 / >51 万㎡）、中交荣域家园（3561 户 / 61.58 万㎡）。
> ⇒ 规模效应必须与「收缴率、单价水平、空置率、楼龄」同时进模型；
>   **不可单以户数解释撤场。**

**⇒ 所以本脚本要回答两个问题**：

| # | 问题 | 判据 |
|---|---|---|
| **Q1** | 撤场案例的**户数分布**是什么样？集中在某个规模区间吗？ | 有户数的案例逐个列出 |
| **Q2** | **单价水平**与**收缴率**是不是比户数更能解释？ | 看案例里的单价与收缴率 |

## ★★ 纪律（skill 3.2 第 6 条）

**样本量极小**（有户数的只有 12 例）⇒
**只做描述性统计，不做任何显著性检验**，并**明确写出"不足以支持回归"**。
必须给出每个数字的案例名，便于溯源。
"""
from __future__ import annotations

import json
import statistics as st
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
EP = ROOT / "episodes" / "2026-W54"
OUT = EP / "results"
OUT.mkdir(parents=True, exist_ok=True)

CASES = json.loads((EP / "data" / "案例库.json").read_text(encoding="utf-8"))

# 行业面（来自取证报告，全部带来源）
INDUSTRY = {
    "全国监测住宅撤场项目_2025初至2026_03": 212,
    "其中2025年撤场": 173,
    "2025年主动撤出或到期不续占比": 0.65,
    "百强物企主动撤场数": 80,
    "百强主动撤场占比": 0.38,
    "楼龄5年内次新房占撤场比": 0.35,
    "TOP50品牌物业主动撤场率同比": 0.37,
    "2025_1至9月公开撤场起数": 120,
    "收缴率生死红线": 0.85,
    "2025年500强平均收缴率": 0.71,
    "上市物企平均收缴率": 0.78,
    "中小物企收缴率": "<0.65（部分<0.50）",
    "行业满意度": 69.1,
    "人力成本占支出比": "0.60–0.70",
    "行业平均毛利率": "0.05–0.20",
    "近五年一审物业服务合同纠纷": 4390000,
    "住宅物业换手率_2021": 0.017,
    "住宅物业换手率_2024": 0.033,
    "每年换物业小区数": 20000,
}


def main() -> int:
    print("=" * 94)
    print("  W54 核心检验 · 撤场跟「规模」有关，还是跟「单价」有关？")
    print("=" * 94)

    print(f"\n-- Q1. 有户数的案例（{sum(1 for c in CASES if c.get('户数'))} 例）--")
    hh = [c for c in CASES if c.get("户数")]
    hh.sort(key=lambda c: c["户数"])
    print(f"  {'小区':<24}{'城市':<10}{'户数':>6}{'单价':>7}"
          f"{'收缴率/欠费线索':<28}")
    for c in hh:
        clue = (c.get("原因") or "")[:26]
        pr = c.get("原单价")
        print(f"  {c['小区'][:22]:<24}{c['城市'][:8]:<10}{c['户数']:>6}"
              f"{(f'{pr:.2f}' if pr else '—'):>7}  {clue}")
    vals = [c["户数"] for c in hh]
    print(f"\n  统计（n={len(vals)}）：中位 {st.median(vals):,.0f} 户｜"
          f"均值 {st.mean(vals):,.0f}｜"
          f"范围 {min(vals):,.0f}–{max(vals):,.0f}")
    small = [c for c in hh if c["户数"] < 1000]
    print(f"  ★ 小于 1000 户的：{len(small)} 例"
          f"（{'、'.join(c['小区'][:14] for c in small)}）")
    print(f"  ★ 大于等于 1000 户的：{len(hh)-len(small)} 例"
          f"（{'、'.join(c['小区'][:14] for c in hh if c['户数'] >= 1000)}）")

    print(f"\n-- Q1b. ★★ 这直接反驳了「只有小项目才撤场」--")
    big = [c for c in hh if c["户数"] >= 1500]
    print(f"  户数 >= 1500 的撤场案例 **{len(big)} 例**：")
    for c in big:
        pr = c.get("原单价")
        print(f"    · {c['小区'][:26]:<28}{c['户数']:>6} 户  "
              f"单价 {(f'{pr:.2f}' if pr else '—'):>5}  "
              f"{(c.get('原因') or '')[:30]}")

    print(f"\n-- Q2. 单价分布（有单价的 {sum(1 for c in CASES if c.get('原单价'))} 例）--")
    pr = sorted((c["原单价"], c["小区"][:20], c["城市"][:6])
                for c in CASES if c.get("原单价"))
    for v, n, city in pr:
        bar = "█" * max(1, int(v * 4))
        print(f"  {v:>5.2f}  {bar:<22}{n}（{city}）")
    pv = [v for v, _n, _c in pr]
    print(f"\n  中位单价 {st.median(pv):.2f}｜均值 {st.mean(pv):.2f}｜"
          f"范围 {min(pv):.2f}–{max(pv):.2f} 元/㎡·月")
    print(f"  ★ 全国基准：20 城均价 2.72｜上海 3.51｜杭州 2.98｜"
          f"重庆指导价上限 1.90")

    print(f"\n-- Q3. ★★ 两个锚点（唯一的保本成本数据）--")
    print(f"  锚点 A：廊坊香河 京澜园+京丰园（万科物业）")
    print(f"    物业费 **1.65** 元/㎡·月，**保本成本需 3 元/㎡以上**")
    print(f"    ⇒ 缺口 >= **{3.0-1.65:.2f}** 元/㎡·月（缺口率 >= "
          f"{(3.0-1.65)/3.0*100:.0f}%）")
    print(f"    ★ 原文强调「5 个社区**财务独立核算**」——")
    print(f"      即同一大盘里的**小组团单独核算就不可持续**")
    print(f"  锚点 B：苏州江湾雅园（本案）")
    print(f"    实测单位成本 **5.5863** 元/㎡·月，收费 4.91")
    print(f"    ⇒ 缺口 **{5.5863-4.91:.4f}** 元/㎡·月（缺口率 "
          f"{(5.5863-4.91)/5.5863*100:.1f}%）")
    print(f"\n  ★★ 把两个锚点并排看：")
    print(f"    {'':<22}{'保本成本':>10}{'实收':>8}{'缺口':>9}")
    print(f"    {'京澜园+京丰园（小）':<22}{3.0:>10.2f}{1.65:>8.2f}"
          f"{3.0-1.65:>9.2f}")
    print(f"    {'江湾雅园（1867户）':<22}{5.5863:>10.4f}{4.91:>8.2f}"
          f"{5.5863-4.91:>9.4f}")
    print(f"    ⇒ **两者都在亏，但原因不同**：")
    print(f"      小项目：**单价太低**（1.65 元，只有保本线的 55%）")
    print(f"      大项目：**单价不低但仍然不够**（4.91 元，是保本线的 88%）")

    print(f"\n-- Q4. 收缴率：比户数更直接的线索？--")
    rate_cases = [
        ("恒隆城", "湖州安吉", "62.82% -> 46.26% -> **16.5%**"),
        ("连城国际", "杭州", "**<50%**；欠费 >1200 万"),
        ("金色水岸", "宁波鄞州", "长期仅 **58%**"),
        ("北樾府", "杭州", "86.34 -> 92.35 -> 86.61 -> **76.43%**"),
        ("六建溪上桃花源", "岳阳湘阴", "前两年 **<60%**"),
        ("中南世纪城康城", "盐城", "欠费 573.74 万，涉及 **60.1%** 户"),
        ("赞成美树", "杭州余杭", "收缴率过低"),
        ("居然雅素里", "重庆", "未缴费业主 **>1/2**"),
    ]
    for n, c, s in rate_cases:
        print(f"  {n:<20}{c:<10}{s}")
    print(f"\n  ★ 行业基准：**85% 是生死红线**；")
    print(f"    2025 年 500 强平均 **71%**（连降 4 年）、上市物企 78%、"
          f"中小 <65%（部分 <50%）")
    print(f"  ⇒ 上面 {len(rate_cases)} 个案例**全部低于或贴近红线**")

    print(f"\n-- Q5. 行业趋势（这才是「会不会越来越多」的正面证据）--")
    for k, v in INDUSTRY.items():
        if isinstance(v, float) and v < 1:
            print(f"  {k:<34}{v*100:>10.2f}%")
        elif isinstance(v, int) and v > 1000:
            print(f"  {k:<34}{v:>10,}")
        else:
            print(f"  {k:<34}{str(v):>10}")

    print(f"\n{'='*94}")
    print("  结论")
    print(f"{'='*94}")
    print(f"  ① **「会不会越来越多」有正面证据**：")
    print(f"     2025-01 至 2026-03 全国监测住宅撤场 **212 个**；")
    print(f"     主动撤场率同比 **+37%**；收缴率 **连降 4 年** 到 71%；")
    print(f"     近五年一审物业服务合同纠纷 **439 万件**。")
    print(f"  ② **但「小项目才撤场」不成立** ——")
    print(f"     户数 >= 1500 的撤场案例有 {len(big)} 例，"
          f"最大 {max(vals):,.0f} 户。")
    print(f"  ③ **更直接的解释变量是「单价 vs 保本成本」的缺口**，"
          f"以及**收缴率**。")
    print(f"  ④ ★ **样本量不足**：有户数的只有 {len(hh)} 例、"
          f"有单价的 {len(pv)} 例、有保本成本的 **1** 例")
    print(f"     ⇒ **本期只能做「结构性论证 + 敏感性区间」，"
          f"不能做显著性检验。**")

    res = {
        "_结论": "撤场不是小项目专属；更直接的解释是「单价 vs 保本成本缺口」与「收缴率」",
        "有户数案例数": len(hh), "有单价案例数": len(pv),
        "有保本成本案例数": 1,
        "户数统计": {"中位": st.median(vals), "均值": st.mean(vals),
                  "最小": min(vals), "最大": max(vals),
                  "小于1000户": sum(1 for v in vals if v < 1000),
                  "大于等于1500户": len(big)},
        "单价统计": {"中位": st.median(pv), "均值": st.mean(pv),
                  "最小": min(pv), "最大": max(pv)},
        "锚点": {
            "京澜园京丰园": {"单价": 1.65, "保本成本": 3.0,
                          "缺口": 1.35, "规模": "体量小、户数少"},
            "江湾雅园": {"单价": 4.91, "保本成本": 5.5863,
                       "缺口": 0.6763, "规模": "1867 户 / 41.54 万㎡"},
        },
        "行业趋势": INDUSTRY,
        "_样本量警告": "不足以做回归或显著性检验；只做描述性统计",
    }
    (OUT / "p2_规模与单价检验.json").write_text(
        json.dumps(res, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"\n  [落盘] {OUT / 'p2_规模与单价检验.json'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
