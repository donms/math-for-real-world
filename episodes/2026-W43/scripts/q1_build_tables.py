def normalize(d: dict[int, float], H: int) -> dict[int, float]:
    sub = {i: d.get(i, 0.0) for i in range(1, H + 1)}
    s = sum(sub.values())
    return {i: (v / s if s else 0.0) for i, v in sub.items()}


